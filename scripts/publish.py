"""Builds the marketplace: finds mods without a release, packs built libraries into .mmc files,
and regenerates index.toml, which the moddedMC app reads.

  python scripts/publish.py plan              ids of mods whose version has no release yet (JSON)
  python scripts/publish.py pack <libs> <out> pack each built mod into <out>/<id>-<version>.mmc
  python scripts/publish.py index <out>       rewrite index.toml from mods/ and the packed files

Layout and fields: README.md.
"""

import hashlib
import json
import re
import subprocess
import sys
import tomllib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = "devmogged/mods"
ID = re.compile(r"^[a-z0-9][a-z0-9-]*$")


def mods():
    """Every mod: (id, version, listing, folder)."""
    out = []
    for folder in sorted((ROOT / "mods").iterdir()):
        if not (folder / "Cargo.toml").is_file():
            continue
        package = tomllib.loads((folder / "Cargo.toml").read_text("utf-8"))["package"]
        listing = tomllib.loads((folder / "mod.toml").read_text("utf-8"))
        mod_id, version = package["name"], package["version"]
        assert ID.match(mod_id) and mod_id == folder.name, f"{folder.name}: crate name must be the folder name"
        for field in ("name", "description", "license"):
            assert isinstance(listing.get(field), str), f"{mod_id}: mod.toml needs {field}"
        out.append((mod_id, version, listing, folder))
    return out


def tag(mod_id, version):
    return f"{mod_id}-v{version}"


def released(mod_id, version):
    return subprocess.run(["gh", "release", "view", tag(mod_id, version), "--repo", REPO],
                          capture_output=True).returncode == 0


def abi_version():
    """The ABI the mods were built against, from the moddedmc-api source cargo fetched."""
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1"], cwd=ROOT))
    api = next(p for p in meta["packages"] if p["name"] == "moddedmc-api")
    abi = (Path(api["manifest_path"]).parent / "src" / "abi.rs").read_text("utf-8")
    return int(re.search(r"ABI_VERSION: u32 = (\d+)", abi).group(1))


def pack(libs, out):
    """<libs>/<platform>/<lib file> from each build job -> <out>/<id>-<version>.mmc."""
    libs, out = Path(libs), Path(out)
    out.mkdir(parents=True, exist_ok=True)
    abi = abi_version()
    for mod_id, version, listing, folder in mods():
        stem = mod_id.replace("-", "_")
        built = {}
        for platform in sorted(p for p in libs.iterdir() if p.is_dir()):
            for name, ext in ((f"{stem}.dll", "dll"), (f"lib{stem}.so", "so"), (f"lib{stem}.dylib", "dylib")):
                if (platform / name).is_file():
                    built[f"{platform.name}.{ext}"] = platform / name
        if not built:
            continue
        manifest = {"id": mod_id, "version": version, "abi": abi}
        if listing.get("dependencies"):
            manifest["dependencies"] = listing["dependencies"]
        path = out / f"{mod_id}-{version}.mmc"
        with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("mod.json", json.dumps(manifest))
            for name, lib in built.items():
                z.write(lib, name)
            # resources/data loads like a datapack; resources/assets goes to players' resource pack.
            for kind in ("data", "assets"):
                base = folder / "resources" / kind
                for file in sorted(base.rglob("*")) if base.is_dir() else []:
                    if file.is_file():
                        z.write(file, f"{kind}/{file.relative_to(base).as_posix()}")
        print(f"packed {path.name}: {', '.join(built)}")


def toml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    return json.dumps(v, ensure_ascii=False)  # a JSON string is a valid TOML basic string


def index(out):
    """index.toml: one entry per mod with a published (or just packed) .mmc."""
    out = Path(out) if out else None
    old = {}
    if (ROOT / "index.toml").is_file():
        old = {m["id"]: m for m in tomllib.loads((ROOT / "index.toml").read_text("utf-8")).get("mods", [])}
    lines = ["# Generated by scripts/publish.py on every publish. Edit mods/<id>/mod.toml instead.", ""]
    for mod_id, version, listing, folder in mods():
        file = f"{mod_id}-{version}.mmc"
        packed = out / file if out else None
        if packed and packed.is_file():
            data = packed.read_bytes()
            sha256, size = hashlib.sha256(data).hexdigest(), len(data)
        elif old.get(mod_id, {}).get("version") == version:
            sha256, size = old[mod_id]["sha256"], old[mod_id]["size"]
        else:
            continue  # not built yet
        original = listing.get("original", {})
        entry = {
            "id": mod_id,
            "name": listing["name"],
            "version": version,
            "kind": "drop-in",
            "description": listing["description"],
            "license": listing["license"],
            "original": f"{original['name']} {original['version']}" if original else None,
            "minecraft": original.get("minecraft"),
            "upstream": original.get("url"),
            "dependencies": listing.get("dependencies", []),
            "icon": f"https://raw.githubusercontent.com/{REPO}/main/mods/{mod_id}/icon.png"
            if (folder / "icon.png").is_file() else None,
            "download": f"https://github.com/{REPO}/releases/download/{tag(mod_id, version)}/{file}",
            "sha256": sha256,
            "size": size,
        }
        lines.append("[[mods]]")
        lines += [f"{k} = {toml_value(v)}" for k, v in entry.items() if v is not None]
        lines.append("")
    (ROOT / "index.toml").write_text("\n".join(lines), "utf-8")
    tomllib.loads((ROOT / "index.toml").read_text("utf-8"))  # self-check: the app must parse it


if __name__ == "__main__":
    command = sys.argv[1]
    if command == "plan":
        print(json.dumps([m for m, v, _, _ in mods() if not released(m, v)]))
    elif command == "pack":
        pack(sys.argv[2], sys.argv[3])
    elif command == "index":
        index(sys.argv[2] if len(sys.argv) > 2 else None)
    else:
        sys.exit(__doc__)
